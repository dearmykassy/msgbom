function buildFaq(node: RegionNode): RegionCustomerCopy["faq"] {
  const baseFaqs = buildRegionServiceFaqs(node.displayName);
  return {
    title: pick(node.path, "faq-title", FAQ_TITLES),
    items: baseFaqs.map((faq, index) => ({
      question: faq.question,
      answer: pick(
        node.path,
        `faq:${index}`,
        FAQ_ANSWER_VARIANTS[index] ?? [faq.answer],
      ),
    })),
  };
}

function buildDirectory(node: RegionNode): RegionCustomerCopy["directory"] {
  const children = getDirectChildren(node);
  const sourceNames = node.representative?.sourceNames ?? [];
  const isSingleSameSource =
    sourceNames.length === 1 && sourceNames[0] === node.displayName;
  const hubExamples = children
    .slice(0, 3)
    .map((child) => child.name)
    .join("·");
  const coverageExamples = sourceNames.slice(0, 3).join("·") || node.displayName;
  const coverageTitle = pick(node.path, "coverage-title", [
    `${node.displayName}에 포함되는 행정동`,
    `${node.displayName} 방문 주소 안내`,
    `${node.displayName} 안내 동네`,
    `${node.displayName}에서 함께 안내하는 동네`,
    `${node.displayName} 포함 주소 확인`,
    `${node.displayName} 행정동 안내`,
    `${node.displayName}에서 확인할 행정동`,
    `${node.displayName}에 포함되는 지역`,
    `${node.displayName}에 연결된 동 이름`,
    `${node.displayName} 상담 지역 범위`,
    `${node.displayName} 주소 안내`,
    `${node.displayName} 포함 동네 안내`,
  ]);

  return {
    title: node.kind === "province"
      ? pick(node.path, "directory-title", [
          `${node.displayName} 시·군·구 선택`,
          `${node.displayName} 하위 지역 찾기`,
          `${node.displayName} 예약 지역 고르기`,
          `${node.displayName} 시·군·구 안내`,
          `${node.displayName} 방문 지역 선택`,
          `${node.displayName} 주소별 페이지`,
        ])
      : pick(node.path, "directory-title", [
          `${node.displayName} 아래 지역 선택`,
          `${node.displayName} 하위 주소 찾기`,
          `${node.displayName} 동네별 안내`,
          `${node.displayName} 예약 지역 고르기`,
          `${node.displayName} 방문지 선택`,
          `${node.displayName} 주소별 페이지`,
        ]),
    lead: children.length > 0
      ? pick(node.path, "directory-lead", DIRECTORY_HUB_LEADS)(hubExamples)
      : isSingleSameSource
        ? pick(
            node.path,
            "directory-single-empty-lead",
            DIRECTORY_SINGLE_COVERAGE_LEADS,
          )(node.displayName)
      : pick(node.path, "directory-empty-lead", DIRECTORY_COVERAGE_LEADS)(
          coverageExamples,
          node.displayName,
        ),
    coverageTitle,
    coverageLead: isSingleSameSource
      ? pick(
          node.path,
          "directory-single-coverage-lead",
          DIRECTORY_SINGLE_COVERAGE_LEADS,
        )(node.displayName)
      : pick(
          node.path,
          "directory-coverage-lead",
          DIRECTORY_COVERAGE_LEADS,
        )(coverageExamples, node.displayName),
  };
}

