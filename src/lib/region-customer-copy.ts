function localDetail(node: RegionNode): string {
  const children = getDirectChildren(node);
  const sourceNames = node.representative?.sourceNames ?? [];

  if (node.kind === "representative") {
    const examples = sourceNames.slice(0, 3).join("·");
    return sourceNames.length > 1
      ? `${examples} 주소의 방문 가능 여부는 전화로 문의하세요.`
      : "실제 방문 주소와 희망 시각을 전화로 알려 방문 가능 여부를 확인하세요.";
  }

  const examples = children.slice(0, 3).map((child) => child.name).join("·");
  return `${examples} 등 실제 주소에 맞는 하위 지역을 고른 뒤 방문 가능 여부를 전화로 확인하세요.`;
}

