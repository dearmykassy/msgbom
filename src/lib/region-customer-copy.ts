function stableHash(value: string): number {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

function pick<T>(
  path: string,
  key: string,
  values: readonly T[],
): T {
  return values[stableHash(`${path}|${key}`) % values.length];
}

function pair(
  path: string,
  key: string,
  openings: readonly string[],
  closings: readonly string[],
): string {
  return `${pick(path, `${key}:opening`, openings)} ${pick(path, `${key}:closing`, closings)}`;
}

