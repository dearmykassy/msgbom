function buildCourseChoice(
  node: RegionNode,
  keywords: ReturnType<typeof buildRegionServiceKeywords>,
): RegionCustomerCopy["courseChoice"] {
  const openingById: Readonly<Record<CourseId, readonly string[]>> = {
    thai: THAI_OPENINGS,
    aroma: AROMA_OPENINGS,
    healing: HEALING_OPENINGS,
    special: SPECIAL_OPENINGS,
    "male-only": MALE_OPENINGS,
  };

  const items = COURSE_SELECTION_GUIDE.map((guide) => {
    let keywordContext = "";
    if (guide.courseId === "thai") {
      keywordContext = `${keywords["출장타이마사지"]}로 알아봤다면 가격표의 타이마사지 코스명과 이용 시간을 기준으로 문의하세요.`;
    } else if (guide.courseId === "aroma") {
      keywordContext = `${keywords["출장홈타이"]}라는 표현으로 찾았더라도 오일 사용 여부와 실제 가격표 코스명을 상담에서 확인하세요.`;
    } else if (guide.courseId === "special") {
      keywordContext = `${keywords["출장스웨디시"]} 또는 ${keywords["토닥이"]}를 찾았다면 화면에 있는 스페셜마사지와 같은 코스라고 단정하지 말고 제공 내용을 먼저 확인하세요.`;
    } else if (guide.courseId === "male-only") {
      keywordContext = `${keywords["남성전용마사지"]} 문의라면 남성전용 코스의 시간과 선호 압을 함께 알려주세요.`;
    }

    return {
      courseId: guide.courseId,
      title: pick(
        node.path,
        `course-title:${guide.courseId}`,
        COURSE_TITLE_VARIANTS[guide.courseId],
      ),
      description: `${pair(
        node.path,
        `course-choice:${guide.courseId}`,
        openingById[guide.courseId],
        CONFIRM_CLOSINGS,
      )}${keywordContext ? ` ${keywordContext}` : ""}`,
      linkLabel: pick(node.path, `course-link:${guide.courseId}`, [
        `${guide.courseName} 가격 확인`,
        `${guide.courseName} 시간별 금액`,
        `${guide.courseName} 가격표 보기`,
        `${guide.courseName} 이용 시간 보기`,
        `${guide.courseName} 코스 금액`,
        `${guide.courseName} 항목으로 이동`,
      ]),
    };
  });

  return {
    title: pick(node.path, "course-section-title", COURSE_SECTION_TITLES),
    lead: pick(node.path, "course-section-lead", COURSE_SECTION_LEADS),
    items,
  };
}

